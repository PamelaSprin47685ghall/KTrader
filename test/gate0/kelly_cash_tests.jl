# =============================================================================
# K-S-R-1 设计 A（§9）：双路径候选比较键（纯函数真值表；T-A1）
# =============================================================================
# 比较键：过证书者优先；同档 q=max(fes,kkt,gap) 小者优先；|Δq|<1e-15 用固定
# 路径序（raw < raw_polished < scaled < scaled_polished）。确定性、无 RNG。
# 集成层锚（cap#5 取缩放不回退 / cap#3 fail-loud）见上方 T1d 断言与本文件
# 既有 testset；两候选都过时的取优由本真值表第 3/4 组覆盖。
@testset "K-S-R-1 design A: dual-path candidate selection" begin
    XcA = reshape([1.2, 0.85], 2, 1)
    c_pass = cash_kelly_certificate(XcA, [5 / 6], 1 / 6; budget=1.0)
    c_fail = cash_kelly_certificate(XcA, [0.0], 1.0; budget=1.0)
    mk(w, c, cert, path) = (; w = w, cert = cert, certified = c, path = path)
    # (1) 过者优先（无论 q）：a 过 b 不过 → a
    a_raw = mk([0.0], true, c_pass, :raw)
    b_scl = mk([0.0], false, c_fail, :scaled)
    @test _pick_better_kelly_candidate(a_raw, b_scl).path == :raw
    @test _pick_better_kelly_candidate(b_scl, a_raw).path == :raw
    # (2) 都不过：q 小者胜（对称）
    c_small = merge(c_fail, (; kkt_residual = 1e-7, objective_gap = 1e-7))
    c_big = merge(c_fail, (; kkt_residual = 5e-7, objective_gap = 5e-7))
    x_raw = mk([0.0], false, c_small, :raw)
    x_scl = mk([0.0], false, c_big, :scaled)
    @test _pick_better_kelly_candidate(x_raw, x_scl).path == :raw
    @test _pick_better_kelly_candidate(x_scl, x_raw).path == :raw
    # (3) 都过：q 小者胜（对称）
    y_raw = mk([0.0], true, merge(c_pass, (; kkt_residual = 1e-8, objective_gap = 1e-8)), :raw)
    y_scl = mk([0.0], true, merge(c_pass, (; kkt_residual = 2e-8, objective_gap = 2e-8)), :scaled)
    @test _pick_better_kelly_candidate(y_raw, y_scl).path == :raw
    @test _pick_better_kelly_candidate(y_scl, y_raw).path == :raw
    # (4) tie（|Δq|<1e-15）：固定路径序 raw > scaled（对称）
    t_raw = mk([0.0], false, merge(c_fail, (; kkt_residual = 1e-7, objective_gap = 1e-7)), :raw)
    t_scl = mk([0.0], false, merge(c_fail, (; kkt_residual = 1e-7, objective_gap = 1e-7)), :scaled)
    @test _pick_better_kelly_candidate(t_raw, t_scl).path == :raw
    @test _pick_better_kelly_candidate(t_scl, t_raw).path == :raw
    # (5) 路径序与确定性
    @test _kelly_candidate_rank(:raw) < _kelly_candidate_rank(:raw_polished) <
          _kelly_candidate_rank(:scaled) < _kelly_candidate_rank(:scaled_polished)
    @test _pick_better_kelly_candidate(x_raw, x_scl) == _pick_better_kelly_candidate(x_raw, x_scl)
end

