    # 深度加深后可能反超 scaled）——断言「采纳方=较优质量方」的语义；固定
    # 「取缩放不回退」的历史口径由 G2 对照保留，不再是本锚的义务。
    let adv_raw = dg5.adopted in (:raw, :raw_polished)
        qa = adv_raw ? dg5.raw_quality : dg5.scaled_quality
        qb = adv_raw ? dg5.scaled_quality : dg5.raw_quality
        @test qa <= qb + 1e-15
    end
    @test cash_kelly_certified(cert5; tol=1e-6)
    @test cert5.kkt_residual <= 1e-6
    @test isapprox(sum(w5) + c5, 1.0; atol=1e-6)
    @test all(x -> x >= -1e-9, w5) && c5 >= -1e-9
    wealth5 = vec(X5 * w5) .+ c5 .+ _cap5_base
    @test isapprox(sum(log, wealth5) / 1024, cert5.objective; atol=1e-8)

    # --- T3 确定性：同输入两次（带诊断）逐位一致 ---
    dgA = KellyScaleDiagnostics(); dgB = KellyScaleDiagnostics()
    wA, cA, certA = cash_kelly(Xc; scale_retry_diag=dgA)
    wB, cB, certB = cash_kelly(Xc; scale_retry_diag=dgB)
    @test wA == wB && cA == cB && certA.objective == certB.objective
    @test dgA.preferred == dgB.preferred && dgA.span == dgB.span
    @test dgA.attempted == dgB.attempted && dgA.rescued == dgB.rescued

    # P1 判决配套：cap#5 输入导出至模块级（T-P1 testset 只读使用；同一内联测试数据）
    global _P1_CAP5_XFREE = _cap5_xfree
    global _P1_CAP5_BASE = _cap5_base
