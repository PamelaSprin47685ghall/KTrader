# P0-9 canonical tie-break（二阶段 canonicalization）
# 裁决书 §P0-9：当 U(w1) ≈ U(w2) 甚至完全相等时，返回哪个最优点不能由
# Clarabel / numerical support 决定。canonical representative：
#   1. U* = max U(w)（含 cash）；
#   2. 在 W_ε = {w : U(w) ≥ U* − tie_eps} 上最大化 w_c；
#   3. 在相同最大 w_c 下最小化 ‖w_risky‖₂²。
# 这不是 regularization，不改变经济目标，只选 optimum set 的 canonical
# representative。tie_eps 默认 1e-8（初始候选，留待 D-066 定稿）。
# =============================================================================
@testset "P0-9 canonical tie-break" begin
    # --- 平局构造：D-090(b) 的对称射线（结构性平局，整条射线都是最优）---
    # X = [1.2 0.9 0.9; 0.9 1.2 0.9; 0.9 0.9 1.2]：行和恒 3.0 ⟹
    # 对称射线 w = (u,u,u)、cash = 1−3u 上 wealth ≡ 1、objective ≡ 0。
    # 射线上 cash 从 1（u=0）到 0（u=1/3）。canonical representative：
    # Stage 2 最大化 cash ⟹ u=0（w_risky=0, cash=1）；
    # Stage 3 在 cash=1 下最小化 risky L2 ⟹ w_risky=0。
    Xb = [1.2 0.9 0.9;
          0.9 1.2 0.9;
          0.9 0.9 1.2]
    wb, cb, certb = cash_kelly(Xb)
    @test all(x -> abs(x) <= 1e-7, wb)          # canonical: 全 cash 端点
    @test abs(cb - 1.0) <= 1e-7
    @test cash_kelly_certified(certb; tol=1e-8)
    @test abs(certb.objective) <= 1e-9          # 平局值 = 0（经济目标未变）

    # --- 平局构造：D-091 无信号世界（连续平局解集，整个单纯形都是最优）---
    # 行 = (1.06, 0.94, 1.0) 全部置换；E[gross_i]=1 ∀i ⟹ Jensen 等号在
    # wealth ≡ 1 处取到。canonical representative 同样选最大 cash 端点。
    Xn = [1.06 0.94 1.0;
          1.06 1.0 0.94;
