# B2B-SPLIT-1（§9.10）：prelude/finish 拆分等价性（与 cash_kelly 逐点一致）
# =============================================================================
@testset "B2B-SPLIT-1: prelude/finish equals cash_kelly" begin
    Xc = reshape([1.2, 0.85], 2, 1)
    cases = Any[(Xc, (;)), (fill(0.99, 4, 2), (;))]
    for (X, kw) in cases
        pre = _cash_kelly_prelude(X; kw...)
        r1 = _cash_kelly_finish(X, pre)
        r2 = cash_kelly(X; kw...)
        @test r1[1] == r2[1] && r1[2] == r2[2]
        @test r1[3].objective == r2[3].objective
        @test r1[3].kkt_residual == r2[3].kkt_residual
        @test r1[3].objective_gap == r2[3].objective_gap
        @test r1[3].feasibility == r2[3].feasibility
    end
    # 退化预算分支（一）：无 base（b=0）→ wealth=0 → 证书不过 → 两边都抛。
    # 探针 S1_probe.log 证实 cash_kelly 抛同一条错；此处断言「行为一致性」：
    # 两者要么都抛且错误文本相同、要么都返回（当前实现为都抛）。
    e1 = try
        _cash_kelly_prelude(Xc; budget = 0.0)
        nothing
    catch err
        sprint(showerror, err)
    end
    e2 = try
        cash_kelly(Xc; budget = 0.0)
        nothing
    catch err
        sprint(showerror, err)
    end
    @test e1 !== nothing && e2 !== nothing && e1 == e2
    # 退化预算分支（二）：base=1>0 → wealth=1>0 → 证书过 → early 直通，
    # 返回 (zeros, 0.0)；prelude+finish 与 cash_kelly 一致。
    pre1 = _cash_kelly_prelude(Xc; base = fill(1.0, size(Xc, 1)), budget = 0.0)
    r1 = _cash_kelly_finish(Xc, pre1)
    r2 = cash_kelly(Xc; base = fill(1.0, size(Xc, 1)), budget = 0.0)
    @test r1[1] == zeros(size(Xc, 2)) && r1[2] == 0.0
    @test r1[1] == r2[1] && r1[2] == r2[2]
    @test r1[3].objective == r2[3].objective
    @test r1[3].kkt_residual == r2[3].kkt_residual
    @test r1[3].objective_gap == r2[3].objective_gap
    # skip_tb 非全 cash 分支（D-091 平局射线）
    Xn = [1.06 0.94 1.0; 1.06 1.0 0.94; 0.94 1.06 1.0;
          0.94 1.0 1.06; 1.0 1.06 0.94; 1.0 0.94 1.06]
    pa = _cash_kelly_prelude(Xn)
    ra = _cash_kelly_finish(Xn, pa)
    rb = cash_kelly(Xn)
    @test ra[1] == rb[1] && ra[2] == rb[2]
    @test ra[3].kkt_residual == rb[3].kkt_residual
    # B2B-SPLIT-2：三件组合（prelude + finish_main + finish_tiebreak）== cash_kelly
    preM = _cash_kelly_prelude(Xc)
    midM = _cash_kelly_finish_main(Xc, preM)
    rM = _cash_kelly_finish_tiebreak(Xc, preM, midM)
    rC = cash_kelly(Xc)
    @test rM[1] == rC[1] && rM[2] == rC[2]
    @test rM[3].kkt_residual == rC[3].kkt_residual
    @test rM[3].objective_gap == rC[3].objective_gap
    preN = _cash_kelly_prelude(Xn)
    midN = _cash_kelly_finish_main(Xn, preN)
    rN = _cash_kelly_finish_tiebreak(Xn, preN, midN)
    rCN = cash_kelly(Xn)
    @test rN[1] == rCN[1] && rN[2] == rCN[2]
    @test !midN.skip_tb                        # 非全 cash：tie 进入分支
    # B2B-SPLIT-3：prep + solve + finish 全链 == cash_kelly
    prepP = _cash_kelly_prelude_prep(Xc)
    solP = _cash_kelly_prelude_solve(Xc, prepP)
    rP = _cash_kelly_finish(Xc, solP)
    rC2 = cash_kelly(Xc)
    @test rP[1] == rC2[1] && rP[2] == rC2[2]
    @test rP[3].kkt_residual == rC2[3].kkt_residual
    prepE = _cash_kelly_prelude_prep(Xc; base = fill(1.0, size(Xc, 1)), budget = 0.0)
    solE = _cash_kelly_prelude_solve(Xc, prepE)
    rE = _cash_kelly_finish(Xc, solE)
    @test rE[1] == zeros(size(Xc, 2)) && rE[2] == 0.0
end

